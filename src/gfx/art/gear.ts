function draw(shape: string, m: Mat, oy = 0, outline = true): PixelCanvas {
  const c = new PixelCanvas(16, 16);
  const rows = SHAPES[shape];
  const top = Math.max(0, Math.floor((16 - rows.length) / 2)) + oy;
  c.rows(rows, 0, top, { a: m.a, b: m.b, c: m.c, h: m.h ?? m.c, x: m.x ?? 'Y', y: m.y ?? 'R', z: m.z ?? 'F' });
  if (outline) c.outline();
  return c;
}

